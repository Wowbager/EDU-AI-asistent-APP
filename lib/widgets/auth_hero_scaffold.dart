import 'dart:math' as math;

import 'package:flutter/material.dart';
import 'package:flutter_svg/flutter_svg.dart';

import '../core/layout/breakpoints.dart';
import '../core/strings/app_strings.dart';
import '../core/theme/app_theme.dart';

/// Root of the wide-window (split-pane) auth-journey layout. Exposed so tests
/// can assert which layout is live without depending on copy or pixel
/// positions. Shared by every screen on the journey (login, age gate,
/// guardian consent), so the key means "the hero-scene layout is live", not
/// "the login form is visible".
const Key splitPaneKey = Key('auth-split-pane');

/// The background ground wave, in whichever layout is live.
const Key waveKey = Key('auth-wave');

/// The cave backdrop layer of the split-pane hero scene.
const Key caveKey = Key('auth-cave');

/// The mascot-and-props layer of the split-pane hero scene.
const Key sceneKey = Key('auth-scene');

/// The mascot-and-props layer as the *sheet* layout draws it — the same
/// artwork, cropped to the props and scaled down (BR-W5HNHB). Distinct from
/// [sceneKey] so tests can still assert that the split-pane's full-artboard
/// layers stay out of the phone layout.
const Key compactSceneKey = Key('auth-compact-scene');

/// The eDU-AI wordmark above the props in the compact hero.
const Key compactWordmarkKey = Key('auth-compact-wordmark');

/// Width of the form column. The phone sheet and the desktop panel use the
/// same value so both layouts share one set of control sizes.
const double kAuthFormColumnWidth = 340;

/// The ground wave that closes off the background, authored full-bleed at
/// 1440×250. Vector, so it stays crisp at any width.
const String kAuthWaveAsset = 'assets/images/login_wave.svg';
const double kAuthWaveAspectRatio = 250 / 1440;

/// The two illustration layers, both authored on the same artboard as the
/// desktop design so placing either one is pure scaling.
const String kAuthCaveAsset = 'assets/images/login_cave.svg';
const String kAuthSceneAsset = 'assets/images/login_scene.svg';
const Size kAuthSceneArtboard = Size(1440, 810);

/// Tight bounding box of the drawn props inside [kAuthSceneAsset], measured
/// from the rendered SVG rather than eyeballed.
///
/// The artwork only occupies the left ~45% of the artboard — on the desktop
/// layout the panel covers the rest — so anything that wants the props
/// centred (the phone sheet) has to offset by this rather than by the
/// artboard. Re-measure if the asset is ever re-exported.
const Rect kAuthPropsRect = Rect.fromLTWH(46, 390, 652, 442);

/// The wordmark used above the props, authored 308.75×89.38 — the tight
/// bounding box of the mark, so a width alone places it exactly.
///
/// Generated by `design/logo/generate.py`; re-run it and update the ratio
/// here if the brand mark is ever redrawn.
const String kAuthWordmarkAsset = 'assets/images/login_logo_wide.svg';
const double kAuthWordmarkAspectRatio = 89.38 / 308.75;

/// Colour the auth wordmark is always drawn in: the default palette's
/// `progressFill`, i.e. the brand purple.
///
/// Read off [ThemeConfig.defaultTheme] rather than written as a literal so the
/// logo follows the palette if the brand purple is ever retuned. It cannot be
/// `const` — reading a field off a const object is not a constant expression.
final Color kAuthWordmarkColour =
    ThemeConfig.defaultTheme.colors.progressFill;

/// The brand wordmark at [width], in the brand purple whatever the active
/// theme is.
///
/// The mark is a single-fill shape, so a `srcIn` filter recolours all of it.
/// The side nav and the dashboard header feed that filter the live
/// `AppColors.progressFill`, which is what lets a custom theme carry the logo
/// with it — but the auth journey deliberately does not (BR-UDENF8). A skin
/// outlives the session that chose it: `_restoreSavedTheme` in `main.dart`
/// reapplies the saved palette at boot, before anything knows whether the user
/// is still signed in, and `ThemeManager.resetToDefault()` only runs on a
/// clean logout. So an expired session drops to a login screen still painted
/// in the previous user's colours, and the first thing the next, possibly
/// unknown, person sees is the brand in someone else's blue.
Widget buildAuthWordmark({required double width, Key? key}) {
  return SvgPicture.asset(
    kAuthWordmarkAsset,
    key: key,
    width: width,
    height: width * kAuthWordmarkAspectRatio,
    colorFilter: ColorFilter.mode(kAuthWordmarkColour, BlendMode.srcIn),
  );
}

/// The background wave at [width], with the height its aspect ratio implies.
///
/// The height has to be given explicitly: unlike [Image], `SvgPicture` does
/// not derive one from the source's intrinsic size, so left to itself inside
/// a bottom-anchored `Positioned` it asks for infinite height and asserts.
/// With the box already at the right ratio, `BoxFit.fill` cannot distort.
Widget buildAuthWave({required double width}) {
  return SizedBox(
    key: waveKey,
    width: width,
    height: width * kAuthWaveAspectRatio,
    child: SvgPicture.asset(kAuthWaveAsset, fit: BoxFit.fill),
  );
}

/// Landscape tablet / desktop scaffold for the auth journey: the illustrated
/// hero scene fills the window and the screen's content sits in the panel on
/// the right, so every step of the journey (login, age gate, guardian
/// consent) keeps the same backdrop and only the panel changes.
///
/// The scene ships as two layers split out of the 1440×810 desktop artboard,
/// so the themed gradient, the ground wave and the localized logo/tagline can
/// stay the separate layers they already are: the cave backdrop hangs from
/// the top-left corner behind the wave, and the props scene (mascot, book,
/// lollipop…) stands on the ground in front of it. Both keep the full
/// artboard viewBox, so placing them is pure scaling.
class AuthHeroScaffold extends StatelessWidget {
  /// Content of the right-hand panel. Rendered inside the panel's scroll
  /// view, vertically centred, capped at [kAuthFormColumnWidth].
  final Widget panel;

  /// When set, a back arrow is pinned to the panel's top-left corner, above
  /// the scrolled content — screens deeper in the journey use it instead of
  /// drawing their own.
  final VoidCallback? onBack;

  /// Widget pinned to the window's top-left corner, over the hero rather
  /// than the panel so it stays on the dark background (the login screen
  /// puts its language switcher here — BR-U75N5Y).
  final Widget? heroOverlay;

  const AuthHeroScaffold({
    super.key,
    required this.panel,
    this.onBack,
    this.heroOverlay,
  });

  static const String _caveAsset = kAuthCaveAsset;
  static const String _sceneAsset = kAuthSceneAsset;
  static const Size _artboard = kAuthSceneArtboard;

  @override
  Widget build(BuildContext context) {
    final size = MediaQuery.sizeOf(context);
    final panelWidth = authPanelWidth(size.width);

    // The props layer shares the wave's transform — scaled by window width,
    // pinned to the bottom-left — so the mascot and props keep standing
    // exactly where the ground curves, at every window width.
    final sceneScale = size.width / _artboard.width;
    // The cave hangs from the top edge instead. On windows taller than the
    // artboard's ratio (an iPad is 1.44:1 vs the artboard's 1.78:1) width
    // scaling alone would end it mid-air, so it grows until it reaches the
    // ground again.
    final caveScale = math.max(sceneScale, size.height / _artboard.height);

    return Scaffold(
      body: Container(
        width: double.infinity,
        height: double.infinity,
        decoration: BoxDecoration(
          gradient: AppColors.authGradient,
        ),
        // The wave is authored full-bleed (1440 wide), so it spans the whole
        // window and runs on behind the panel rather than stopping at the
        // hero.
        child: Stack(
          key: splitPaneKey,
          children: [
            Positioned(
              left: 0,
              top: 0,
              child: SizedBox(
                key: caveKey,
                width: _artboard.width * caveScale,
                height: _artboard.height * caveScale,
                child: SvgPicture.asset(_caveAsset, fit: BoxFit.fill),
              ),
            ),
            Positioned(
              left: 0,
              bottom: 0,
              child: buildAuthWave(width: size.width),
            ),
            Positioned(
              left: 0,
              bottom: 0,
              child: SizedBox(
                key: sceneKey,
                width: _artboard.width * sceneScale,
                height: _artboard.height * sceneScale,
                child: SvgPicture.asset(_sceneAsset, fit: BoxFit.fill),
              ),
            ),
            Row(
              children: [
                const Expanded(child: _HeroPane()),
                Padding(
                  // Insets taken from the design: 24 top, 20 right, 28 bottom.
                  padding: const EdgeInsets.fromLTRB(0, 24, 20, 28),
                  child: SizedBox(
                    width: panelWidth,
                    child: _buildPanel(),
                  ),
                ),
              ],
            ),
            if (heroOverlay != null)
              Positioned(
                top: 0,
                left: 0,
                child: SafeArea(
                  child: Padding(
                    padding: const EdgeInsets.only(top: 8, left: 16),
                    child: heroOverlay,
                  ),
                ),
              ),
          ],
        ),
      ),
    );
  }

  Widget _buildPanel() {
    return DecoratedBox(
      decoration: BoxDecoration(
        gradient: AppColors.authPanelGradient,
        borderRadius: BorderRadius.circular(20),
      ),
      child: SafeArea(
        child: Stack(
          children: [
            LayoutBuilder(
              builder: (context, constraints) {
                // Centre the content vertically, but fall back to scrolling
                // once the panel is shorter than the content (short windows,
                // or the sign-up mode which is taller).
                return SingleChildScrollView(
                  padding: const EdgeInsets.symmetric(
                    horizontal: 24,
                    vertical: 32,
                  ),
                  child: ConstrainedBox(
                    constraints: BoxConstraints(
                      minHeight: constraints.maxHeight - 64,
                    ),
                    child: Center(
                      child: ConstrainedBox(
                        constraints: const BoxConstraints(
                          maxWidth: kAuthFormColumnWidth,
                        ),
                        child: panel,
                      ),
                    ),
                  ),
                );
              },
            ),
            if (onBack != null)
              Positioned(
                top: 8,
                left: 8,
                child: IconButton(
                  icon: const Icon(Icons.arrow_back),
                  onPressed: onBack,
                ),
              ),
          ],
        ),
      ),
    );
  }
}

/// Left pane of the split-pane layout: logo + tagline.
///
/// The ground, the cave and the mascot scene are drawn by the full-bleed
/// layers behind this pane; only the localized copy lives here. The desktop
/// artboard uses the plain wordmark (the mascot already stands below it),
/// unlike the phone layout's character logo.
class _HeroPane extends StatelessWidget {
  const _HeroPane();

  @override
  Widget build(BuildContext context) {
    return Align(
      alignment: const Alignment(0, -0.35),
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          buildAuthWordmark(width: 309),
          const SizedBox(height: 16),
          Text(
            AppStrings.authHeroTaglineExpanded,
            style: AppTextStyles.heading2(color: Colors.white),
          ),
        ],
      ),
    );
  }
}

/// The hero scene reduced to what fits above the phone sheet: the wordmark
/// over the mascot-and-props cluster (BR-W5HNHB).
///
/// The sheet layout used to show only the character logo, leaving a wide band
/// of empty gradient above it, while the wide layout already had the full
/// illustrated scene. This reuses that same artwork rather than shipping a
/// second one — the props are cropped out of the desktop artboard via
/// [kAuthPropsRect] and centred, since on the artboard they sit off to the
/// left where the desktop panel does not cover them.
///
/// The whole block scales down to [maxHeight] instead of being clipped: the
/// sheet grows from 52% to 72% of the screen when the form switches to
/// sign-up mode, and the keyboard shrinks the body further, so the band above
/// the wave is not a constant. It never scales *up* past the design size —
/// on a tall phone the composition stays put and the extra room stays empty.
///
/// The wide layout's tagline is deliberately dropped here: its string is
/// `authHeroTaglineExpanded`, sized for a hero pane that has room to spare,
/// and on a phone the same height is worth more to the artwork.
class AuthCompactHero extends StatelessWidget {
  /// Room between the top safe-area inset and the composition's baseline.
  final double maxHeight;

  const AuthCompactHero({super.key, required this.maxHeight});

  /// Share of the viewport the props span before the absolute cap applies.
  static const double _widthFraction = 0.88;

  /// Absolute cap, so a portrait tablet does not get artwork wider than the
  /// desktop draws it — and keeps the composition in scale with the
  /// [kAuthFormColumnWidth] form beneath it.
  static const double _maxWidth = 400;

  /// Wordmark width as a share of the props width, taken from the desktop
  /// artboard (309 against the 652-wide props cluster ≈ 0.47) and nudged up
  /// so the lockup still reads at phone sizes.
  static const double _wordmarkFraction = 0.55;

  static const double _gap = 8;

  @override
  Widget build(BuildContext context) {
    final designWidth =
        math.min(MediaQuery.sizeOf(context).width * _widthFraction, _maxWidth);
    final propsHeight =
        designWidth * kAuthPropsRect.height / kAuthPropsRect.width;
    final wordmarkWidth = designWidth * _wordmarkFraction;
    final wordmarkHeight = wordmarkWidth * kAuthWordmarkAspectRatio;
    final designHeight = wordmarkHeight + _gap + propsHeight;

    final scale =
        maxHeight <= 0 ? 0.0 : math.min(maxHeight / designHeight, 1.0);

    return Column(
      mainAxisSize: MainAxisSize.min,
      children: [
        buildAuthWordmark(
          key: compactWordmarkKey,
          width: wordmarkWidth * scale,
        ),
        SizedBox(height: _gap * scale),
        _AuthProps(width: designWidth * scale),
      ],
    );
  }
}

/// Just the props cluster of [kAuthSceneAsset], sized so the box *is* the
/// artwork.
///
/// `SvgPicture` cannot be handed a viewBox, so the full artboard is rendered
/// oversized inside a box the size of [kAuthPropsRect] and pulled up and left
/// until the crop lines up. Nothing needs clipping — the rest of the artboard
/// is transparent.
class _AuthProps extends StatelessWidget {
  final double width;

  const _AuthProps({required this.width});

  @override
  Widget build(BuildContext context) {
    final scale = width / kAuthPropsRect.width;

    return SizedBox(
      key: compactSceneKey,
      width: width,
      height: kAuthPropsRect.height * scale,
      child: Stack(
        clipBehavior: Clip.none,
        children: [
          Positioned(
            left: -kAuthPropsRect.left * scale,
            top: -kAuthPropsRect.top * scale,
            width: kAuthSceneArtboard.width * scale,
            height: kAuthSceneArtboard.height * scale,
            child: SvgPicture.asset(kAuthSceneAsset, fit: BoxFit.fill),
          ),
        ],
      ),
    );
  }
}
